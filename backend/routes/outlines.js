// POST /api/outlines/suggest
router.post('/suggest', async (req, res) => {
  const { text } = req.body;
  if (!text || !text.trim()) {
    return res.status(400).json({ error: 'text 필드가 필요합니다' });
  }

  if (!process.env.OPENAI_API_KEY) {
    const keywords = text.toLowerCase();
    const suggested = OUTLINES.filter(o =>
      keywords.includes(o.name) || keywords.includes(o.category)
    ).slice(0, 4);
    return res.json({ suggested: suggested.length ? suggested : OUTLINES.slice(0, 4) });
  }

  try {
    const client = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });
    const nameList = OUTLINES.map(o => o.name).join(', ');

    const response = await client.chat.completions.create({
      model: 'gpt-4o-mini',
      max_tokens: 60,
      messages: [{
        role: 'user',
        content: `다음 윤곽선 목록 중에서 아래 텍스트 내용과 가장 관련 있는 것 최대 4개를 골라주세요.
윤곽선 목록: ${nameList}
텍스트: "${text}"
응답 형식: 윤곽선 이름만 쉼표로 구분해서 반환 (예: 강아지, 꽃, 태양)`
      }]
    });

    const raw = response.choices[0].message.content.trim();
    const names = raw.split(',').map(s => s.trim()).filter(Boolean);
    const suggested = names
      .map(n => OUTLINES.find(o => o.name === n))
      .filter(Boolean);

    res.json({ suggested: suggested.length ? suggested : OUTLINES.slice(0, 4) });
  } catch (err) {
    console.error('outline suggest error:', err.message);
    res.status(500).json({ error: '추천 중 오류가 발생했습니다' });
  }
});

export default router;
